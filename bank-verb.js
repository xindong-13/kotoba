/* 對單一字串做變化（傳進來的可以是漢字表記或假名） */
function conjStr(s, type, form, flag){
  const stem=s.slice(0,-1), last=s.slice(-1);
  if(type===2){
    return {masu:stem+"ます",masen:stem+"ません",mashita:stem+"ました",te:stem+"て",nai:stem+"ない",
      ta:stem+"た",pot:stem+"られる",vol:stem+"よう",ba:stem+"れば",pass:stem+"られる",
      caus:stem+"させる",imp:stem+"ろ",tai:stem+"たい"}[form];
  }
  // 五段
  if(flag==="aru"&&form==="nai") return "ない";
  if(flag==="iku"){ if(form==="te") return stem+"って"; if(form==="ta") return stem+"った"; }
  return {
    masu:   stem+U2I[last]+"ます",
    masen:  stem+U2I[last]+"ません",
    mashita:stem+U2I[last]+"ました",
    tai:    stem+U2I[last]+"たい",
    te:     stem+TE1[last],
    ta:     stem+TA1[last],
    nai:    stem+U2A[last]+"ない",
    pass:   stem+U2A[last]+"れる",
    caus:   stem+U2A[last]+"せる",
    pot:    stem+U2E[last]+"る",
    ba:     stem+U2E[last]+"ば",
    imp:    stem+U2E[last],
    vol:    stem+U2O[last]+"う"
  }[form];
}

/* 回傳 {k:漢字表記, r:假名} */
window.conjV = function(v, form){
  if(v.t===3){
    if(v.r==="くる"){ const r=KURU[form]; return {k:"来"+r.slice(1), r:r}; }
    const bk=v.d.slice(0,-2), br=v.r.slice(0,-2), sfx=SURU[form];
    return {k:bk+sfx, r:br+sfx};
  }
  return { k:conjStr(v.d,v.t,form,v.x), r:conjStr(v.r,v.t,form,v.x) };
};

